import { build } from "esbuild";
import {
  mkdir,
  copyFile,
  readdir,
  readFile,
  writeFile,
  rm,
} from "node:fs/promises";
import { createHash } from "node:crypto";

await mkdir("assets", { recursive: true });
// Remove only generated JavaScript, so obsolete chunks cannot linger in the offline cache.
for (const entry of await readdir("assets"))
  if (
    /^(app|chunk-|pdf-|archive-|rtf-|jspdf|purify|html2canvas|__commonJS).*(\.js|\.js\.LEGAL\.txt)$/.test(
      entry,
    )
  )
    await rm(`assets/${entry}`);
await build({
  entryPoints: ["src/main.js"],
  outdir: "assets",
  entryNames: "app",
  chunkNames: "chunk-[hash]",
  bundle: true,
  splitting: true,
  format: "esm",
  target: ["es2022"],
  minify: true,
  legalComments: "external",
  metafile: false,
});
await copyFile(
  "node_modules/pdfjs-dist/build/pdf.worker.min.mjs",
  "assets/pdf.worker.min.mjs",
);
for (const dir of ["cmaps", "standard_fonts", "wasm"]) {
  await mkdir(`assets/${dir}`, { recursive: true });
  for (const name of await readdir(`node_modules/pdfjs-dist/${dir}`))
    await copyFile(
      `node_modules/pdfjs-dist/${dir}/${name}`,
      `assets/${dir}/${name}`,
    );
}
const files = [
  "index.html",
  "style.css",
  "sw.js",
  "favicon.ico",
  "icon.png",
  "icon-192.png",
  "icon-512.png",
  "site.webmanifest",
];
async function walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = `${dir}/${entry.name}`;
    if (entry.isDirectory()) await walk(path);
    else if (path !== "assets/precache.js") files.push(path);
  }
}
await walk("assets");
files.sort();
const hash = createHash("sha256");
for (const file of files) hash.update(await readFile(file));
await writeFile(
  "assets/precache.js",
  `// Generated by npm run build.\nself.EAZYREAD_CACHE="eazyread-${hash.digest("hex").slice(0, 12)}";\nself.EAZYREAD_ASSETS=${JSON.stringify(files.map((path) => "./" + path))};\n`,
);
console.log(
  `Built EazyRead with ${files.length} local assets. No runtime CDN requests.`,
);
